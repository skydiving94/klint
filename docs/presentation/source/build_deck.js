// Builds the architecture deck: architecture.pptx, architecture.pdf and
// speaker_notes.md in docs/presentation/.
//
//   npm install && node build_deck.js [--screenshots <folder>]
//
// The PDF is printed by headless Google Chrome from the same slide specs
// that make the .pptx. --screenshots also writes one PNG per slide, and the
// build fails when a text box overflows.

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");
const PptxGenJS = require("pptxgenjs");

const { drawSlideInPptx, writeDeckHtml } = require("./render");
const story = require("./slides_story");
const design = require("./slides_design");
const changeSummary = require("./slides_change_summary");

const OUTPUT_FOLDER = path.resolve(__dirname, "..");
const CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";

function buildSlideSpecs() {
  return [
    story.buildTitleSlide(),
    story.buildObjectivesSlide(),
    design.buildLayersSlide(),
    design.buildPortsSlide(),
    design.buildSuitesSlide(),
    design.buildRunSlide(),
    changeSummary.buildVerificationSlide(),
    changeSummary.buildResultsSlide(),
    changeSummary.buildExtensibilitySlide(),
    story.buildQualitySlide(),
    story.buildDebtSlide(),
    story.buildTradeOffsSlide(),
    story.buildRecommendationSlide(),
  ];
}

async function writePptx(specs, outputPath) {
  const pres = new PptxGenJS();
  pres.layout = "LAYOUT_WIDE";
  pres.title = "klint architecture";
  pres.subject = "Issue #22: architecture overhaul, as built";
  pres.author = "klint wave 6";
  specs.forEach((spec) => drawSlideInPptx(pres, spec));
  await pres.writeFile({ fileName: outputPath });
}

function runChrome(args) {
  execFileSync(CHROME, ["--headless=new", "--disable-gpu", "--hide-scrollbars", ...args], {
    stdio: "pipe",
  });
}

function writePdf(htmlPath, outputPath) {
  runChrome(["--no-pdf-header-footer", `--print-to-pdf=${outputPath}`, `file://${htmlPath}`]);
}

// Writes one PNG per slide and returns the text boxes that overflow.
function writeScreenshots(specs, folder) {
  fs.mkdirSync(folder, { recursive: true });
  const overflowing = [];
  specs.forEach((spec, index) => {
    const htmlPath = path.join(folder, `slide-${index + 1}.html`);
    fs.writeFileSync(htmlPath, writeDeckHtml([spec]));
    runChrome([
      "--window-size=1280,720",
      `--screenshot=${path.join(folder, `slide-${String(index + 1).padStart(2, "0")}.png`)}`,
      `file://${htmlPath}`,
    ]);
    const dom = execFileSync(CHROME, ["--headless=new", "--disable-gpu", "--dump-dom", `file://${htmlPath}`], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    for (const match of dom.matchAll(/data-overflow="([^"]*)"/g)) {
      overflowing.push(`slide ${index + 1}: ${match[1]}`);
    }
  });
  return overflowing;
}

function writeSpeakerNotes(specs, outputPath) {
  const sections = specs.map((spec, index) => {
    const title = spec.items.find((item) => item.kind === "text" && item.name === "Title");
    const heading = title ? title.paragraphs : index === 0 ? "klint" : "Recommendation";
    return `## ${index + 1}. ${heading}\n\n${spec.notes}\n`;
  });
  const header = [
    "# klint architecture deck: speaker notes",
    "",
    "The notes of `architecture.pptx`, slide by slide. They name the files and classes behind each claim, on branch `wave-6`.",
    "Generated by `source/build_deck.js`; edit the slides there and rebuild.",
    "",
  ].join("\n");
  fs.writeFileSync(outputPath, `${header}\n${sections.join("\n")}`);
}

async function main() {
  const specs = buildSlideSpecs();
  const pptxPath = path.join(OUTPUT_FOLDER, "architecture.pptx");
  const pdfPath = path.join(OUTPUT_FOLDER, "architecture.pdf");
  await writePptx(specs, pptxPath);
  const workFolder = fs.mkdtempSync(path.join(os.tmpdir(), "klint-deck-"));
  const htmlPath = path.join(workFolder, "architecture.html");
  fs.writeFileSync(htmlPath, writeDeckHtml(specs));
  writePdf(htmlPath, pdfPath);
  writeSpeakerNotes(specs, path.join(OUTPUT_FOLDER, "speaker_notes.md"));
  console.log(`Wrote ${pptxPath}, ${pdfPath} and speaker_notes.md (${specs.length} slides)`);

  const screenshotFlag = process.argv.indexOf("--screenshots");
  if (screenshotFlag !== -1) {
    const folder = path.resolve(process.argv[screenshotFlag + 1]);
    const overflowing = writeScreenshots(specs, folder);
    console.log(`Wrote screenshots to ${folder}`);
    if (overflowing.length) {
      console.error(`Text that does not fit:\n${overflowing.join("\n")}`);
      process.exitCode = 1;
    }
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
